#!/usr/bin/env bash
# Prepare one pinned C6 environment, shared by the application guide and CI.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
workspace="$(realpath -m "${ROS2_ZEPHYR_C6_WORKSPACE:-$root/build/c6/workspace}")"
pin=8f04542
# Full immutable revision is checked below; this repository supplies source locks,
# not application code or a benchmark runtime dependency.
revision=8f04542f344fdd63f5eb1728805a42f30432d03b
if [[ ! -d "$workspace/.git" ]]; then
  git clone --no-checkout https://github.com/servoagents/ros2-embedded-benchmarks.git "$workspace"
  git -C "$workspace" checkout --detach "$revision"
fi
[[ "$(git -C "$workspace" rev-parse HEAD)" == "$revision" ]] || {
  echo "C6 workspace revision differs from the locked environment ($pin)." >&2; exit 1;
}
python3.14 -m venv "$workspace/.venv"
# Generated by venv above.
# shellcheck disable=SC1091
source "$workspace/.venv/bin/activate"
python -m pip install -r "$workspace/config/python-requirements.lock" -r "$workspace/config/sdk-requirements.lock"
python "$workspace/scripts/prepare.py" "$@"
# west flash needs extension discovery even when the SDK is supplied.
if [[ ! -d "$workspace/deps/.west" ]]; then
  (cd "$workspace"; west init -l deps/zephyr)
fi
sdk="$(realpath -m "${ZEPHYR_SDK_INSTALL_DIR:-$workspace/.local/sdk}")"
if [[ ! -f "$sdk/sdk_version" ]]; then
  (cd "$workspace/deps"; west sdk install --version 1.0.1 --install-dir "$sdk" --gnu-toolchains riscv64-zephyr-elf)
fi
[[ "$(cat "$sdk/sdk_version")" == 1.0.1 ]]
[[ "$("$sdk/gnu/riscv64-zephyr-elf/bin/riscv64-zephyr-elf-gcc" -dumpfullversion)" == 14.3.0 ]]
mkdir -p "$root/build/c6"
{
  printf 'export ROS2_ZEPHYR_C6_WORKSPACE=%q\n' "$workspace"
  printf 'export ZEPHYR_SDK_INSTALL_DIR=%q\n' "$sdk"
  printf 'source %q\n' "$workspace/.venv/bin/activate"
} > "$root/build/c6/env.sh"
printf 'Environment ready. Run: source %q\n' "$root/build/c6/env.sh"
